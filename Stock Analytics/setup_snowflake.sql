-- ==============================================================================
-- Stock Analytics Platform (Multi-Exchange) - Initial Setup
-- ==============================================================================

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE STOCK_ANALYTICS_WH;

-- 1. Create Database
CREATE DATABASE IF NOT EXISTS STOCK_ANALYTICS_DB
    COMMENT = 'Database for Multi-Exchange Stock Analytics Platform';

USE DATABASE STOCK_ANALYTICS_DB;

-- 2. Create Schemas (Medallion Architecture + Ops + Semantic)
CREATE SCHEMA IF NOT EXISTS BRONZE
    COMMENT = 'Raw data ingestion layer loaded via Snowpipe';

CREATE SCHEMA IF NOT EXISTS SILVER
    COMMENT = 'Cleaned, typed, and standardized layer transformed by dbt';

CREATE SCHEMA IF NOT EXISTS GOLD
    COMMENT = 'Star schema layer with dimensions and facts transformed by dbt';

CREATE SCHEMA IF NOT EXISTS OPS
    COMMENT = 'Operational audit logs and rejected records';

CREATE SCHEMA IF NOT EXISTS SEMANTIC
    COMMENT = 'Business-ready semantic views for Streamlit and analytics';

-- 3. Create File Format for CSVs
CREATE OR REPLACE FILE FORMAT BRONZE.CSV_FORMAT
    TYPE = 'CSV'
    FIELD_DELIMITER = ','
    RECORD_DELIMITER = '\n'
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF = ('', 'NULL', 'null')
    EMPTY_FIELD_AS_NULL = TRUE
    ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE;

-- 4. Create Snowflake Internal Stage
CREATE OR REPLACE STAGE BRONZE.STOCK_STAGE
    FILE_FORMAT = BRONZE.CSV_FORMAT
    DIRECTORY = (ENABLE = TRUE)
    COMMENT = 'Internal stage for landing CSV feeds: exchanges, companies, prices, corporate actions';

-- ==============================================================================
-- 5. Create Bronze / RAW Tables
