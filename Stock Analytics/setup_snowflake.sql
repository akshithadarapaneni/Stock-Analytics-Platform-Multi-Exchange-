    FILE_FORMAT = (FORMAT_NAME = 'BRONZE.CSV_FORMAT')
    ON_ERROR = 'CONTINUE';

-- Pipe 4: Corporate Actions
CREATE OR REPLACE PIPE BRONZE.PIPE_CORPORATE_ACTIONS
