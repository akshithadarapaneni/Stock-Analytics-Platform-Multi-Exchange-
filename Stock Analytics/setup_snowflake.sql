-- ==============================================================================
-- 6. Create OPS Audit & Rejects Tables
-- ==============================================================================

CREATE OR REPLACE TABLE OPS.LOAD_AUDIT (
    BATCH_ID VARCHAR,
    ENTITY_NAME VARCHAR,
    FILE_NAME VARCHAR,
    ROWS_LOADED NUMBER,
    STATUS VARCHAR,
    LOAD_START_TIME TIMESTAMP_NTZ,
    LOAD_END_TIME TIMESTAMP_NTZ,
    ERROR_MESSAGE VARCHAR
);

CREATE OR REPLACE TABLE OPS.REJECTS (
    REJECT_ID VARCHAR DEFAULT UUID_STRING(),
    ENTITY_NAME VARCHAR,
    FILE_NAME VARCHAR,
    ROW_NUMBER NUMBER,
    ERROR_MESSAGE VARCHAR,
    RECORD_DATA VARCHAR,
    REJECT_TIMESTAMP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- ==============================================================================
-- 7. Create Snowpipes (One pipe per entity)
-- ==============================================================================

-- Pipe 1: Exchanges
CREATE OR REPLACE PIPE BRONZE.PIPE_EXCHANGES
    AUTO_INGEST = FALSE
    AS
    COPY INTO BRONZE.RAW_EXCHANGES (
        EXCHANGE_ID, EXCHANGE_CODE, COUNTRY, CURRENCY, TIMEZONE,
        MARKET_TYPE, STATUS, ESTABLISHED_DATE, UPDATED_AT,
        METADATA_LOAD_TS, METADATA_FILE_NAME, METADATA_ROW_NUMBER
    )
    FROM (
        SELECT 
            s.$1, s.$2, s.$3, s.$4, s.$5, 
            s.$6, s.$7, s.$8, s.$9,
            CURRENT_TIMESTAMP(),
            METADATA$FILENAME,
            METADATA$FILE_ROW_NUMBER
        FROM @BRONZE.STOCK_STAGE/exchanges/ s
    )
    FILE_FORMAT = (FORMAT_NAME = 'BRONZE.CSV_FORMAT')
    ON_ERROR = 'CONTINUE';

-- Pipe 2: Companies
CREATE OR REPLACE PIPE BRONZE.PIPE_COMPANIES
    AUTO_INGEST = FALSE
    AS
    COPY INTO BRONZE.RAW_COMPANIES (
        COMPANY_ID, TICKER, COMPANY_NAME, SECTOR, INDUSTRY,
        MARKET_CAP_BAND, COUNTRY, PRIMARY_EXCHANGE_ID, STATUS, LISTED_SINCE, UPDATED_AT,
        METADATA_LOAD_TS, METADATA_FILE_NAME, METADATA_ROW_NUMBER
    )
    FROM (
        SELECT 
            s.$1, s.$2, s.$3, s.$4, s.$5,
            s.$6, s.$7, s.$8, s.$9, s.$10, s.$11,
            CURRENT_TIMESTAMP(),
            METADATA$FILENAME,
            METADATA$FILE_ROW_NUMBER
        FROM @BRONZE.STOCK_STAGE/companies/ s
    )
    FILE_FORMAT = (FORMAT_NAME = 'BRONZE.CSV_FORMAT')
    ON_ERROR = 'CONTINUE';

-- Pipe 3: Daily Prices
CREATE OR REPLACE PIPE BRONZE.PIPE_PRICES_DAILY
    AUTO_INGEST = FALSE
