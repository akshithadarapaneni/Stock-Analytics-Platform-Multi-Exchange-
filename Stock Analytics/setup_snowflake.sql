-- ==============================================================================
-- 8. Basic RBAC Roles (Least Privilege)
-- ==============================================================================

CREATE ROLE IF NOT EXISTS ROLE_INGEST COMMENT = 'Role for data ingestion tasks';
CREATE ROLE IF NOT EXISTS ROLE_ETL COMMENT = 'Role for transformation pipelines (dbt)';
CREATE ROLE IF NOT EXISTS ROLE_ANALYST COMMENT = 'Role for analysts querying Gold and Semantic layers';
CREATE ROLE IF NOT EXISTS ROLE_APP_STREAMLIT COMMENT = 'Role for Streamlit application read-only access';

-- Grant warehouse usage
GRANT USAGE ON WAREHOUSE STOCK_ANALYTICS_WH TO ROLE ROLE_INGEST;
GRANT USAGE ON WAREHOUSE STOCK_ANALYTICS_WH TO ROLE ROLE_ETL;
GRANT USAGE ON WAREHOUSE STOCK_ANALYTICS_WH TO ROLE ROLE_ANALYST;
GRANT USAGE ON WAREHOUSE STOCK_ANALYTICS_WH TO ROLE ROLE_APP_STREAMLIT;

-- Grant database usage
GRANT USAGE ON DATABASE STOCK_ANALYTICS_DB TO ROLE ROLE_INGEST;
GRANT USAGE ON DATABASE STOCK_ANALYTICS_DB TO ROLE ROLE_ETL;
GRANT USAGE ON DATABASE STOCK_ANALYTICS_DB TO ROLE ROLE_ANALYST;
GRANT USAGE ON DATABASE STOCK_ANALYTICS_DB TO ROLE ROLE_APP_STREAMLIT;

-- Ingestion role accesses Bronze and Ops
GRANT USAGE, CREATE STAGE, CREATE PIPE, CREATE TABLE ON SCHEMA BRONZE TO ROLE ROLE_INGEST;
GRANT ALL ON SCHEMA OPS TO ROLE ROLE_INGEST;

-- ETL role accesses Bronze (read), Silver (full), Gold (full)
GRANT USAGE ON SCHEMA BRONZE TO ROLE ROLE_ETL;
GRANT SELECT ON ALL TABLES IN SCHEMA BRONZE TO ROLE ROLE_ETL;
GRANT ALL ON SCHEMA SILVER TO ROLE ROLE_ETL;
GRANT ALL ON SCHEMA GOLD TO ROLE ROLE_ETL;

-- Analyst & Streamlit roles access Semantic and Gold (read-only)
GRANT USAGE ON SCHEMA GOLD TO ROLE ROLE_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA GOLD TO ROLE ROLE_ANALYST;
GRANT USAGE ON SCHEMA SEMANTIC TO ROLE ROLE_ANALYST;
GRANT USAGE ON SCHEMA SEMANTIC TO ROLE ROLE_APP_STREAMLIT;
